#!/usr/bin/env node
/**
 * One-off generator for `src/bench/datasets-real.ts`.
 *
 * Samples publicly available benchmarks so the A/B harness runs on real
 * exercises instead of only hand-written ones:
 *   - GSM8K (OpenAI grade-school math)          -> arithmetic, exact numeric grading
 *   - BBH logical_deduction_three_objects        -> logic, multiple-choice grading
 *   - HotpotQA distractor validation             -> multi-hop factual, web grading
 *
 * Sources:
 *   https://github.com/openai/grade-school-math
 *   https://github.com/suzgunmirac/BIG-Bench-Hard (mirror: lukaemon/bbh on HF)
 *   https://hotpotqa.github.io
 *
 * Usage: node scripts/fetch-real-benchmarks.js
 * Deterministic: fixed offsets, no randomness.
 */

const fs = require('fs');
const path = require('path');

const GSM8K_URL =
  'https://raw.githubusercontent.com/openai/grade-school-math/master/grade_school_math/data/test.jsonl';
const BBH_URL =
  'https://datasets-server.huggingface.co/rows?dataset=lukaemon%2Fbbh&config=logical_deduction_three_objects&split=test&offset=0&length=100';
const HOTPOT_URL =
  'https://datasets-server.huggingface.co/rows?dataset=hotpotqa%2Fhotpot_qa&config=distractor&split=validation&offset=0&length=100';

const GSM8K_TARGET = 25;
const GSM8K_STEP = 53;
const GSM8K_START = 7;
const BBH_TARGET = 12;
const BBH_STEP = 3;
const HOTPOT_TARGET = 15;
const HOTPOT_STEP = 7;

async function fetchText(url) {
  const response = await fetch(url);
  if (!response.ok) {
    throw new Error(`GET ${url} -> ${response.status}`);
  }
  return response.text();
}

async function fetchJson(url) {
  return JSON.parse(await fetchText(url));
}

function escapeTs(value) {
  return JSON.stringify(value);
}

function gsm8kTasks(text) {
  const lines = text.split('\n').filter((line) => line.trim().length > 0);
  const tasks = [];
  for (let i = 0; tasks.length < GSM8K_TARGET && i < lines.length; i += 1) {
    const index = (GSM8K_START + tasks.length * GSM8K_STEP) % lines.length;
    const row = JSON.parse(lines[index]);
    const final = row.answer.split('####').pop().trim().replace(/,/g, '');
    const numeric = Number.parseFloat(final);
    if (!Number.isFinite(numeric)) {
      continue;
    }
    tasks.push({
      id: `gsm8k-${String(index).padStart(4, '0')}`,
      category: 'arithmetic',
      difficulty: 2,
      question: row.question.replace(/\s+/g, ' ').trim(),
      referenceAnswer: `Nombre final: ${final}`,
      keyFacts: [String(numeric)],
      numericAnswer: numeric,
      requiresWeb: false,
      source: 'GSM8K test',
    });
  }
  return tasks;
}

function bbhTasks(payload) {
  const rows = payload.rows ?? [];
  const tasks = [];
  for (let i = 0; tasks.length < BBH_TARGET && i < rows.length; i += BBH_STEP) {
    const row = rows[(i * BBH_STEP) % rows.length]?.row;
    if (!row) {
      continue;
    }
    const letter = String(row.target ?? '').replace(/[^A-Za-z]/g, '').toUpperCase();
    if (!letter) {
      continue;
    }
    tasks.push({
      id: `bbh-${String(i).padStart(3, '0')}`,
      category: 'logic',
      difficulty: 3,
      question: String(row.input).replace(/\s+/g, ' ').trim(),
      referenceAnswer: `Choix ${letter}`,
      keyFacts: [],
      expectedLetter: letter,
      requiresWeb: false,
      source: 'BBH logical_deduction_three_objects',
    });
  }
  return tasks;
}

function hotpotTasks(payload) {
  const rows = payload.rows ?? [];
  const difficultyByLevel = { easy: 1, medium: 2, hard: 3 };
  const tasks = [];
  for (let i = 0; tasks.length < HOTPOT_TARGET && i < rows.length; i += 1) {
    const row = rows[(i * HOTPOT_STEP + 3) % rows.length]?.row;
    if (!row || typeof row.question !== 'string' || typeof row.answer !== 'string') {
      continue;
    }
    tasks.push({
      id: `hotpot-${String(i).padStart(3, '0')}`,
      category: 'factual',
      difficulty: difficultyByLevel[row.level] ?? 2,
      question: row.question.replace(/\s+/g, ' ').trim(),
      referenceAnswer: row.answer,
      keyFacts: [row.answer],
      requiresWeb: true,
      source: 'HotpotQA distractor validation',
    });
  }
  return tasks;
}

function render(tasks) {
  const lines = [];
  lines.push('/**');
  lines.push(' * Generated by scripts/fetch-real-benchmarks.js — do not edit by hand.');
  lines.push(' * Real benchmark samples: GSM8K (arithmetic), BBH (logic), HotpotQA (multi-hop factual).');
  lines.push(' */');
  lines.push("import type { BenchTask } from './types';");
  lines.push('');
  lines.push('export const REAL_BENCH_TASKS: BenchTask[] = [');
  for (const task of tasks) {
    lines.push('  {');
    lines.push(`    id: ${escapeTs(task.id)},`);
    lines.push(`    category: ${escapeTs(task.category)},`);
    lines.push(`    difficulty: ${task.difficulty},`);
    lines.push(`    question: ${escapeTs(task.question)},`);
    lines.push(`    referenceAnswer: ${escapeTs(task.referenceAnswer)},`);
    lines.push(`    keyFacts: ${JSON.stringify(task.keyFacts)},`);
    if (task.numericAnswer !== undefined) {
      lines.push(`    numericAnswer: ${task.numericAnswer},`);
    }
    if (task.expectedLetter) {
      lines.push(`    expectedLetter: ${escapeTs(task.expectedLetter)},`);
    }
    lines.push(`    requiresWeb: ${task.requiresWeb},`);
    lines.push(`    source: ${escapeTs(task.source)},`);
    lines.push('  },');
  }
  lines.push('];');
  lines.push('');
  return lines.join('\n');
}

async function main() {
  console.log('Fetching GSM8K…');
  const gsm8k = gsm8kTasks(await fetchText(GSM8K_URL));
  console.log(`  ${gsm8k.length} tasks`);

  console.log('Fetching BBH…');
  const bbh = bbhTasks(await fetchJson(BBH_URL));
  console.log(`  ${bbh.length} tasks`);

  console.log('Fetching HotpotQA…');
  const hotpot = hotpotTasks(await fetchJson(HOTPOT_URL));
  console.log(`  ${hotpot.length} tasks`);

  const output = path.join(__dirname, '..', 'src', 'bench', 'datasets-real.ts');
  fs.writeFileSync(output, render([...gsm8k, ...bbh, ...hotpot]), 'utf8');
  console.log(`Wrote ${output}`);
}

main().catch((error) => {
  console.error(error);
  process.exitCode = 1;
});
